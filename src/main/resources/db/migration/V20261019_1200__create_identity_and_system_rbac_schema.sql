CREATE TABLE tenants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_tenants_status CHECK (status IN ('PENDING_SETUP', 'ACTIVE', 'DISABLED'))
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants (id),
    email VARCHAR(320) NOT NULL,
    display_name VARCHAR(120) NOT NULL,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'DISABLED', 'WITHDRAWN')),
    CONSTRAINT ck_users_email_nonblank CHECK (email = BTRIM(email) AND email <> ''),
    CONSTRAINT ck_users_display_name_nonblank CHECK (display_name = BTRIM(display_name) AND display_name <> '')
);

CREATE UNIQUE INDEX uq_users_email_case_insensitive ON users (LOWER(email));
CREATE INDEX ix_users_tenant_id ON users (tenant_id);

CREATE TABLE user_credentials (
    user_id BIGINT PRIMARY KEY REFERENCES users (id),
    password_hash VARCHAR(255) NOT NULL,
    password_change_required BOOLEAN NOT NULL DEFAULT FALSE,
    password_changed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_user_credentials_password_hash CHECK (
        LENGTH(password_hash) >= 40
        AND (password_hash LIKE '$%' OR password_hash LIKE '{%}%')
    )
);

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants (id),
    code VARCHAR(64) NOT NULL,
    name VARCHAR(120) NOT NULL,
    protected BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_roles_tenant_code UNIQUE (tenant_id, code),
    CONSTRAINT ck_roles_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE INDEX ix_roles_tenant_id ON roles (tenant_id);

CREATE TABLE resources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants (id),
    parent_id BIGINT REFERENCES resources (id),
    resource_type VARCHAR(16) NOT NULL,
    name VARCHAR(120) NOT NULL,
    permission_identifier VARCHAR(160),
    sort_order INTEGER NOT NULL DEFAULT 0,
    route_path VARCHAR(512),
    icon VARCHAR(120),
    status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_resources_tenant_permission UNIQUE (tenant_id, permission_identifier),
    CONSTRAINT ck_resources_type CHECK (resource_type IN ('GROUP', 'MENU', 'BUTTON')),
    CONSTRAINT ck_resources_permission_shape CHECK (
        (resource_type = 'BUTTON' AND permission_identifier IS NOT NULL)
        OR (resource_type IN ('GROUP', 'MENU') AND permission_identifier IS NULL)
    ),
    CONSTRAINT ck_resources_route_shape CHECK (
        (resource_type = 'MENU') OR route_path IS NULL
    ),
    CONSTRAINT ck_resources_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE INDEX ix_resources_tenant_parent ON resources (tenant_id, parent_id);

CREATE TABLE role_resource (
    role_id BIGINT NOT NULL REFERENCES roles (id),
    resource_id BIGINT NOT NULL REFERENCES resources (id),
    PRIMARY KEY (role_id, resource_id)
);

CREATE INDEX ix_role_resource_resource_id ON role_resource (resource_id);

CREATE TABLE user_role (
    user_id BIGINT NOT NULL REFERENCES users (id),
    role_id BIGINT NOT NULL REFERENCES roles (id),
    PRIMARY KEY (user_id, role_id)
);

CREATE INDEX ix_user_role_role_id ON user_role (role_id);

CREATE TABLE audit_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants (id),
    actor_user_id BIGINT NOT NULL REFERENCES users (id),
    action VARCHAR(160) NOT NULL,
    target_type VARCHAR(80) NOT NULL,
    target_id VARCHAR(120) NOT NULL,
    outcome VARCHAR(32) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_audit_records_outcome CHECK (outcome IN ('SUCCESS', 'FAILURE'))
);

CREATE INDEX ix_audit_records_tenant_created ON audit_records (tenant_id, created_at DESC);

