CREATE TABLE tenant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'DISABLED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    email VARCHAR(320) NOT NULL,
    name VARCHAR(255),
    status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'DISABLED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX users_email_uq ON users (email);

CREATE TABLE user_credential (
    user_id BIGINT PRIMARY KEY,
    password VARCHAR(255) NOT NULL,
    reset_token CHAR(64),
    reset_expires_at TIMESTAMPTZ,
    reset_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT user_credential_reset_state_ck CHECK (
        (reset_token IS NULL AND reset_expires_at IS NULL AND reset_at IS NULL)
        OR (reset_token IS NOT NULL AND reset_expires_at IS NOT NULL)
    )
);

CREATE UNIQUE INDEX user_credential_reset_token_uq
    ON user_credential (reset_token)
    WHERE reset_token IS NOT NULL;

CREATE TABLE resource (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    code VARCHAR(128) NOT NULL,
    name VARCHAR(255) NOT NULL,
    type VARCHAR(16) NOT NULL CHECK (type IN ('MENU', 'ACTION')),
    parent_id BIGINT,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'DISABLED')),
    route VARCHAR(255),
    icon VARCHAR(128),
    sort_order INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT resource_code_uq UNIQUE (code),
    CONSTRAINT resource_tree_ck CHECK (parent_id IS DISTINCT FROM id),
    CONSTRAINT resource_shape_ck CHECK (type <> 'ACTION' OR route IS NULL)
);

CREATE TABLE "role" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE user_role (
    tenant_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    PRIMARY KEY (tenant_id, user_id, role_id)
);

CREATE TABLE role_resource (
    tenant_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    resource_id BIGINT NOT NULL,
    PRIMARY KEY (tenant_id, role_id, resource_id)
);

CREATE TABLE system_setting (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(16) NOT NULL UNIQUE CHECK (type IN ('SETUP', 'GENERAL')),
    setting JSONB NOT NULL CHECK (jsonb_typeof(setting) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

